def seed_knowledge_if_empty(vector_store: VectorStoreManager) -> None:
    """如果知识库为空则注入种子数据"""
    total = sum(vector_store.count(name) for name in vector_store.COLLECTIONS)
    if total == 0 and vector_store.available:
        KnowledgeSeeder(vector_store).seed_all()
    elif not vector_store.available:
        logger.warning("向量库不可用，跳过知识注入")
