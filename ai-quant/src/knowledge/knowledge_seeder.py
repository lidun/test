"""知识库种子数据注入：将金融领域知识写入向量库"""
from __future__ import annotations

from loguru import logger

from src.knowledge.vector_store import VectorStoreManager


class KnowledgeSeeder:
    def __init__(self, vector_store: VectorStoreManager):
        self.vs = vector_store

    def seed_all(self, force: bool = False):
        logger.info("开始注入种子知识...")
        self._seed_factor_research()
        self._seed_strategy_patterns()
        self._seed_market_regimes()
        self._seed_academic_papers()
        self._seed_trading_rules()
        self._seed_risk_management()
        self._seed_strategy_history()
        logger.info("种子知识注入完成")

